def _stock_warehouses(company, pvf=None):
    """Warehouses whose stock is printed: those mapped to the point de vente (with their children) when a
    mapping exists, otherwise every warehouse of the company."""
    if pvf and frappe.get_meta("Warehouse").has_field("dgi_point_of_sale"):
        mapped = frappe.get_all("Warehouse", filters={"company": company, "dgi_point_of_sale": pvf},
                                fields=["lft", "rgt"])
        names = set()
        for w in mapped:
            names.update(frappe.get_all("Warehouse", filters={"company": company, "lft": [">=", w.lft],
                                                              "rgt": ["<=", w.rgt]}, pluck="name"))
        if names:
            return sorted(names)
    return frappe.get_all("Warehouse", filters={"company": company}, pluck="name")


def _a_add(articles, si, it, f):
    code = si.item_code or it.get("code") or it.get("name")
    a = articles.setdefault(code, {
        "code": code, "name": si.item_name or it.get("name"), "price": 0.0,
        "group": it.get("taxGroup"), "rate": flt((f["groups"].get(it.get("taxGroup")) or {}).get("rate")),
        "qty_sold": 0.0, "qty_returned": 0.0, "amount": 0.0, "stock": None})
    qty = flt(it.get("quantity"))
    amount = round2(flt(it.get("price")) * qty)
    if f["type"] in CREDIT_TYPES:
        a["qty_returned"] = round(a["qty_returned"] + qty, 3)
        a["amount"] = round2(a["amount"] - amount)
    else:
        a["qty_sold"] = round(a["qty_sold"] + qty, 3)
        a["amount"] = round2(a["amount"] + amount)
        a["price"] = flt(it.get("price"))


def _a_result(articles, company, pvf=None, stock_items=None):
    warehouses = None
    for code, a in articles.items():
        if stock_items.setdefault(code, bool(frappe.db.exists("Item", code)
                                             and frappe.db.get_value("Item", code, "is_stock_item"))):
            if warehouses is None:
                warehouses = _stock_warehouses(company, pvf)
            a["stock"] = round(flt(frappe.db.sql(
                "select sum(actual_qty) from `tabBin` where item_code=%s and warehouse in %s",
                (code, tuple(warehouses) or ("",)))[0][0]), 3) if warehouses else 0.0
    rows = sorted(articles.values(), key=lambda r: str(r["code"]))
    return {"articles": rows,
            "summary": {"count": len(rows),
                        "amount": round2(sum(r["amount"] for r in rows)),
                        "qty_sold": round(sum(r["qty_sold"] for r in rows), 3),
                        "qty_returned": round(sum(r["qty_returned"] for r in rows), 3)}}


def compute_a(company, start, end):
    whole, per_pvf = OrderedDict(), {}
    for row in _registered_invoices(company, start, end):
        f = _invoice_fiscal(row)
        si_items = frappe.get_all("Sales Invoice Item", filters={"parent": row.name},
                                  fields=["item_code", "item_name", "idx"], order_by="idx asc")
        scope = per_pvf.setdefault(row.get("dgi_point_of_sale") or NO_PVF, OrderedDict())
        for si, it in zip(si_items, f["items"]):
            _a_add(whole, si, it, f)
            _a_add(scope, si, it, f)
    stock_items = {}
    out = _a_result(whole, company, None, stock_items)
    out["points_of_sale"] = [dict(pvf_identity(pvf), **_a_result(per_pvf[pvf], company, pvf, stock_items))
                             for pvf in _pvf_order(per_pvf)]
    return out



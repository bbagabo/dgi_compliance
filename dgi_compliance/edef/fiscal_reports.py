class _XZ:
    """Totals of one scope (one point de vente, or the whole company)."""

    def __init__(self):
        self.by_type = OrderedDict((t, {"count": 0, "incomplete": 0, "total": 0.0, "ht": 0.0, "vat": 0.0, "ts": 0.0})
                                   for t in INVOICE_TYPES)
        self.by_type_group = OrderedDict((t, OrderedDict((g, {"total": 0.0, "ht": 0.0, "vat": 0.0, "ts": 0.0})
                                                          for g in GROUPS)) for t in INVOICE_TYPES)
        self.pay = OrderedDict((p, {"sales": 0.0, "credits": 0.0}) for p in PAYMENT_TYPES)
        self.reductions = OrderedDict((t, {"amount": 0.0, "tax": 0.0}) for t in INVOICE_TYPES)
        self.natures = OrderedDict((n, {"count": 0, "total": 0.0}) for n in NATURES)

    def add(self, f):
        t = f["type"] if f["type"] in self.by_type else "FV"
        s = self.by_type[t]
        s["count"] += 1
        for k in ("total", "ht", "vat", "ts"):
            s[k] = round2(s[k] + f["vtotal" if k == "vat" else k])
        for g, v in f["groups"].items():
            cell = self.by_type_group[t].setdefault(g, {"total": 0.0, "ht": 0.0, "vat": 0.0, "ts": 0.0})
            for k in ("total", "ht", "vat", "ts"):
                cell[k] = round2(cell[k] + flt(v.get(k)))
        side = "credits" if t in CREDIT_TYPES else "sales"
        for ptype, amount in f["payments"].items():
            cell = self.pay.setdefault(ptype, {"sales": 0.0, "credits": 0.0})
            cell[side] = round2(cell[side] + amount)
        self.reductions[t]["amount"] = round2(self.reductions[t]["amount"] + f["reductions"])
        self.reductions[t]["tax"] = round2(self.reductions[t]["tax"] + f["reductions_tax"])
        if t in CREDIT_TYPES and f["nature"] in self.natures:
            self.natures[f["nature"]]["count"] += 1
            self.natures[f["nature"]]["total"] = round2(self.natures[f["nature"]]["total"] + f["total"])

    def add_incomplete(self, by_type):
        for t, n in (by_type or {}).items():
            if t in self.by_type:
                self.by_type[t]["incomplete"] += n

    def result(self):
        by_type = self.by_type
        sales = [by_type[t] for t in INVOICE_TYPES if t not in CREDIT_TYPES]
        credits = [by_type[t] for t in CREDIT_TYPES]
        return {
            "by_type": by_type,
            "by_type_group": self.by_type_group,
            "payments": [{"type": p, "label": PAYMENT_LABELS.get(p, p), "sales": v["sales"],
                          "credits": v["credits"], "net": round2(v["sales"] - v["credits"])}
                         for p, v in self.pay.items()],
            "reductions": self.reductions,
            "natures": [{"code": n, "label": NATURES[n], **v} for n, v in self.natures.items()],
            "incomplete_total": sum(v["incomplete"] for v in by_type.values()),
            "summary": {
                "count": sum(v["count"] for v in by_type.values()),
                "sales_total": round2(sum(v["total"] for v in sales)),
                "credits_total": round2(sum(v["total"] for v in credits)),
                "net_total": round2(sum(v["total"] for v in sales) - sum(v["total"] for v in credits)),
                "net_vat": round2(sum(v["vat"] for v in sales) - sum(v["vat"] for v in credits)),
            },
        }


def compute_xz(company, start, end):
    whole, per_pvf = _XZ(), {}
    for row in _registered_invoices(company, start, end):
        f = _invoice_fiscal(row)
        whole.add(f)
        per_pvf.setdefault(row.get("dgi_point_of_sale") or NO_PVF, _XZ()).add(f)
    for pvf, by_type in _incomplete_by_type(company, start, end).items():
        whole.add_incomplete(by_type)
        per_pvf.setdefault(pvf, _XZ()).add_incomplete(by_type)
    out = whole.result()
    out["points_of_sale"] = [dict(pvf_identity(pvf), **per_pvf[pvf].result()) for pvf in _pvf_order(per_pvf)]
    return out



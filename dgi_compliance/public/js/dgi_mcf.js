	class Station {
		constructor({ server, journal, device, config = {}, onState, log, reconnect } = {}) {
			this.server = server; this.journal = journal; this.dev = device;
			this.reconnect = reconnect || null;      // async () => MCFDevice | null (port unplugged then plugged back)
			this.cfg = Object.assign({ expected_nid: "", expected_nif: "", tolerance: 1, pending_timeout_s: 90,
				station_poll_interval_s: 15, heartbeat_interval_s: 60 }, config);
			this.executor = null;
			this.setDevice(device);
			this.state = { server: "inconnu", device: device ? "connecte" : "absent", blocked: false, done: 0, last_error: "" };
			this.onState = onState || (() => {});
			this.log = log || (() => {});
			this.lastHeartbeat = -1e12;
			this._stop = false; this._wake = null; this.running = false;
		}
		setDevice(device) {
			this.dev = device || null;
			this.executor = device ? new Executor(device, this.journal, { tolerance: this.cfg.tolerance,
				pendingTimeout: Number(this.cfg.pending_timeout_s) * 1000 }) : null;
		}
		async dropDevice() {
			const dev = this.dev;
			this.setDevice(null);
			if (dev) { try { await dev.close(); } catch (e) { /* already closed */ } }
		}
		setState(patch) { Object.assign(this.state, patch); this.onState(Object.assign({}, this.state)); }
		wake() { if (this._wake) { const w = this._wake; this._wake = null; w(); } }
		stop() { this._stop = true; this.wake(); }
		_sleep(ms) {
			return new Promise((resolve) => {
				const t = setTimeout(() => { this._wake = null; resolve(); }, ms);
				this._wake = () => { clearTimeout(t); resolve(); };
			});
		}

		async reconcileJournal() {
			for (const entry of await this.journal.openOperations()) {
				const op = Object.assign({}, entry.payload || {}, { operation_id: entry.op_id, lease_token: entry.lease_token });
				const res = await this.dev.lock(() => this.executor.check(op));
				this.log(`rapprochement de ${entry.op_id} : ${res.outcome}`);
				if (res.outcome === "uncertain") { this.setState({ blocked: true }); return false; }
			}
			this.setState({ blocked: false });
			return true;
		}
		async flushResults() {
			for (const entry of await this.journal.undelivered()) {
				try {
					await this.server.result(entry.result);
					await this.journal.markDelivered(entry.op_id);
				} catch (e) {
					if (e instanceof ServerError && [404, 409, 410].includes(e.status)) await this.journal.markDelivered(entry.op_id);
					else throw e;
				}
			}
		}
		async heartbeat(force = false) {
			if (!force && now() - this.lastHeartbeat < this.cfg.heartbeat_interval_s * 1000) return;
			const snap = { gateway_version: VERSION, host: hostInfo(), device_state: this.state.device,
				blocked: this.state.blocked, open_operations: (await this.journal.openOperations()).length };
			if (this.dev) {
				try {
					const [st, srv] = await this.dev.lock(async () => [await this.dev.status(), await this.dev.serverStatus()]);
					this.lastStatus = st;
					Object.assign(snap, { mid: st.mid, nid: st.nid, nif: st.nif, tc: st.tc, last_invoice: st.dfn, last_sig: st.dfs,
						tax_rates: st.tax_rates, flags: st.flags, invoice_open: st.invoice_open, device_time: st.dt,
						dgi_last_sync: srv.last_sync, dgi_pending: srv.pending, dgi_sent: srv.sent, dgi_state: srv.state, port: this.dev.port });
				} catch (e) {
					if (!(e instanceof LinkError)) throw e;
					snap.device_error = e.message;
				}
			}
			snap.gateway_time = iso();
			await this.server.heartbeat(snap);
			this.lastHeartbeat = now();
		}
		async process(op) {
			const devInfo = op.device || {};
			if (this.cfg.expected_nid && devInfo.nid && devInfo.nid !== this.cfg.expected_nid) {
				await this.server.event("NID_OPERATION_INATTENDU", "operation destinee a un autre MCF", { op: op.operation_id });
				return null;
			}
			const res = await this.executor.execute(op);
			this.log(`${op.op_type || "NORMALIZE"} ${(op.invoice || {}).fn || op.fn || ""} : ${res.outcome}${res.error ? " (" + res.error.code + ")" : ""}`);
			try {
				const answer = (await this.server.result(res)) || {};
				await this.journal.markDelivered(op.operation_id);
				if (res.outcome === "normalized") this.setState({ done: this.state.done + 1 });
				return answer.next || null;
			} catch (e) {
				this.log(`resultat ${op.operation_id} non livre (${e.message}) : nouvel essai au prochain cycle`);
				return null;
			}
		}
		/** One cycle; returns the delay (ms) before the next one. */
		async runOnce() {
			try {
				if (!this.dev && this.reconnect) {
					const dev = await this.reconnect();
					if (dev) { this.setDevice(dev); this.setState({ device: "connecte (" + dev.port + ")" }); }
				}
				if (!this.dev) { this.setState({ device: "absent" }); await this.heartbeat(); return 10000; }
				if (!(await this.reconcileJournal())) { await this.heartbeat(); return 5000; }
				await this.flushResults();
				await this.heartbeat();
				try {
					this.lastStatus = await this.dev.lock(() => this.executor.checkDevice(this.cfg.expected_nid || null, this.cfg.expected_nif || null));
				} catch (e) {
					if (!(e instanceof WrongDevice)) throw e;
					this.setState({ device: "refuse : " + e.message, last_error: e.message });
					await this.server.event(e.code, e.message, { status: { mid: e.status.mid, nif: e.status.nif } });
					return 15000;
				}
				let op = (await this.server.lease()) || {};
				let worked = false;
				while (op.operation_id && !this._stop) { worked = true; op = (await this.process(op)) || {}; }
				this.setState({ server: "connecte", device: "connecte (" + this.dev.port + ")" });
				return worked ? 200 : Math.max(2000, Number(this.cfg.station_poll_interval_s || 15) * 1000);
			} catch (e) {
				if (e instanceof Unreachable) { this.setState({ server: "injoignable", last_error: e.message }); return 10000; }
				if (e instanceof LinkError) {
					this.setState({ device: "liaison perdue", last_error: e.message });
					await this.dropDevice();
					return 5000;
				}
				if (e instanceof ServerError) {
					this.setState({ server: e.message, last_error: e.message });
					return [401, 403].includes(e.status) ? 30000 : 10000;
				}
				this.setState({ last_error: String(e && e.message || e) });
				return 10000;
			}
		}
		async run() {
			this.running = true;
			try {
				while (!this._stop) {
					const delay = await this.runOnce();
					if (this._stop) break;
					await this._sleep(delay);
				}
			} finally { this.running = false; }
		}
	}

	function hostInfo() {
		const nav = typeof navigator !== "undefined" ? navigator : {};
		return { browser: (nav.userAgent || "node").slice(0, 160), gateway_version: VERSION,
			platform: nav.platform || "", language: nav.language || "" };
	}

	// ======================================================================= Web Serial transport
	class WebSerialTransport {
		constructor(port, { baudRate = 115200 } = {}) {
			this.port = port; this.baudRate = baudRate; this.buf = []; this.waiter = null;
			this.error = null; this.closed = false;
			const info = port.getInfo ? port.getInfo() : {};
			this.name = info.usbVendorId ? `USB ${info.usbVendorId.toString(16).padStart(4, "0")}:${(info.usbProductId || 0).toString(16).padStart(4, "0")}` : "port serie";
		}
		async open() {
			await this.port.open({ baudRate: this.baudRate, dataBits: 8, stopBits: 1, parity: "none", flowControl: "none", bufferSize: 4096 });
			this.writer = this.port.writable.getWriter();
			this.pump = this._pump();
			return this;
		}
		async _pump() {
			while (this.port.readable && !this.closed) {
				this.reader = this.port.readable.getReader();
				try {
					for (;;) {
						const { value, done } = await this.reader.read();
						if (done) break;
						for (const b of value) this.buf.push(b);
						if (this.waiter) { const w = this.waiter; this.waiter = null; w(); }
					}
				} catch (e) {
					this.error = e;
				} finally {
					try { this.reader.releaseLock(); } catch (e) { /* closed */ }
				}
				if (this.error) break;
			}
			if (this.waiter) { const w = this.waiter; this.waiter = null; w(); }
		}
		_check() {
			if (this.error || this.closed) throw new LinkError(`port serie ferme ou MCF debranche${this.error ? " : " + this.error.message : ""}`);
		}
		async write(bytes) {
			this._check();
			try { await this.writer.write(bytes); } catch (e) { this.error = e; this._check(); }
		}
		async read(n, timeoutMs) {
			this._check();
			if (!this.buf.length) {
				await new Promise((resolve) => {
					const t = setTimeout(() => { this.waiter = null; resolve(); }, Math.max(1, timeoutMs));
					this.waiter = () => { clearTimeout(t); resolve(); };
				});
			}
			if (!this.buf.length) { this._check(); return new Uint8Array(0); }
			return Uint8Array.from(this.buf.splice(0, n));
		}
		resetInput() { this.buf.length = 0; }
		async close() {
			this.closed = true;
			try { if (this.reader) await this.reader.cancel(); } catch (e) { /* ignore */ }
			try { if (this.writer) this.writer.releaseLock(); } catch (e) { /* ignore */ }
			try { await this.port.close(); } catch (e) { /* ignore */ }
		}
	}


	const REFUSAL_CODES = [
		["MONTANT N'EST PAS VALIDE", "MONTANT_INVALIDE", false, "Le total TTC ou TVA envoye ne correspond pas aux montants enregistres par le MCF."],
		["IFU", "TAUX_CHANGE_REFUSE", false, "Le MCF a refuse le taux de change a l'ouverture de la facture. La facture n'est pas normalisee sans son taux (regle v5.0.5 : le taux saisi sur la facture est transmis)."],
		["PAS PU ETRE VERIFI", "AVOIR_NON_VERIFIABLE", true, "Le MCF n'a pas pu verifier l'avoir aupres du serveur DGI (pas de reseau). Reessayez plus tard."],
		["NIF INVALIDE", "NIF_INVALIDE", false, "Le MCF a refuse le NIF du vendeur ou les donnees du client."],
		["DEJA UTILISE", "NUMERO_DEJA_UTILISE", false, "Ce numero est celui de la derniere facture normalisee par le MCF."],
		["MEMOIRE PLEINE", "MEMOIRE_PLEINE", false, "La memoire du MCF est pleine : contactez le fournisseur."],
		["GROUPE DE TAXATION", "GROUPE_INCONNU_MCF", false, "Le MCF ne connait pas ce groupe de taxation : mise a jour du MCF necessaire."],
		["MODE DE PAIEMENT", "PAIEMENT_INCONNU_MCF", false, "Le MCF refuse ce mode de paiement (credit : verifiez la lettre configuree dans ERPNext)."],
	];
	const fold = (t) => (t || "").normalize("NFKD").replace(/[̀-ͯ]/g, "").toUpperCase();
	function classifyRefusal(text) {
		const f = fold(text);
		for (const [needle, code, retryable, message] of REFUSAL_CODES) if (f.includes(needle)) return [code, retryable, message];
		return ["REFUS_MCF", false, "Le MCF a refuse la commande."];
	}

	class Executor {
		constructor(device, journal, { tolerance = 1.0, pendingTimeout = 90000, pendingInterval = 1500 } = {}) {
			this.dev = device; this.journal = journal;
			this.tolerance = Number(tolerance); this.pendingTimeout = pendingTimeout; this.pendingInterval = pendingInterval;
		}
		result(op, outcome, { data, code, message, retryable = false, deviceText, proven = false } = {}) {
			const res = {
				operation_id: op.operation_id, lease_token: op.lease_token, op_type: op.op_type || "NORMALIZE",
				outcome, data: data || {}, steps: this.dev.exchanges.slice(-60),
			};
			if (code || message) res.error = { code: code || "ERREUR", message: message || "", retryable: Boolean(retryable), device_text: deviceText || "" };
			if (proven) res.proven_not_normalized = true;
			return res;
		}
		async checkDevice(expectedNid, expectedNif) {
			const st = await this.dev.status();
			if (!st.mid) throw new WrongDevice("ETAT_ILLISIBLE", "Reponse C1h incomplete : identite du MCF inconnue.", st);
			if (expectedNid && st.nid !== expectedNid)
				throw new WrongDevice("NID_INATTENDU", `MCF branche : NID ${st.nid} ; ce poste est autorise pour le NID ${expectedNid}.`, st);
			if (expectedNif && st.nif !== expectedNif)
				throw new WrongDevice("NIF_INATTENDU", `Le MCF est configure pour le NIF ${st.nif}, la societe a le NIF ${expectedNif}.`, st);
			const blocking = (st.flags || []).filter((f) => BLOCKING_FLAGS.includes(f));
			if (blocking.length) throw new WrongDevice("MCF_BLOQUE", "Etat du MCF bloquant : " + blocking.join(", "), st);
			return st;
		}
		static securityData(raw, { machineMv, machineMt, recovered = false, source = "38h" } = {}) {
			const data = Object.assign({}, raw);
			data.sig = (data.sig || "").replace(/-/g, "").toUpperCase();
			data.qr = qrContent(data.mid || "", data.sig, data.nif || "", data.dt || "");
			data.recovered = recovered; data.source = source;
			if (machineMv !== undefined) { data.machine_mv = machineMv; data.machine_mt = machineMt === undefined ? null : machineMt; }
			return data;
		}
		fromStatus(st, invType, opened) {
			let fc = (opened || {}).fc;
			if (!fc) fc = CREDIT_TYPES.includes(invType) ? st.frc : st.fvc;
			const raw = { fc, tc: st.tc, ft: st.dft || invType, dt: st.dfdt, mid: st.mid, nif: st.nif, fn: st.dfn, sig: st.dfs };
			return Executor.securityData(raw, { machineMv: toFloat(st.dmv), recovered: true, source: "C1h" });
		}
		async cancelQuietly() {
			try {
				const text = await this.dev.cancel();
				return fold(text).includes("ANNUL") || !invoiceOpen(this.dev.lastSta);
			} catch (e) { return false; }
		}
		async reject(op, opts) {
			const res = this.result(op, "rejected", opts);
			await this.journal.setState(op.operation_id, "REJECTED", { result: res });
			return res;
		}

		async normalize(op) {
			this.dev.exchanges = [];
			const inv = op.invoice, devInfo = op.device || {};
			const entry = await this.journal.recordReceived(op);
			if (["DONE", "REJECTED"].includes(entry.state) && entry.result) return entry.result;
			if (["OPENING", "FINALIZING", "UNCERTAIN"].includes(entry.state)) return this.check(op);
			const previous = await this.journal.findDoneByFn(inv.fn);
			if (previous && previous.op_id !== op.operation_id && previous.result) {
				const res = this.result(op, "normalized", { data: Object.assign({}, previous.result.data, { replay_of: previous.op_id }) });
				await this.journal.setState(op.operation_id, "DONE", { result: res });
				return res;
			}
			let st;
			try {
				st = await this.checkDevice(devInfo.nid, devInfo.nif || inv.nif);
			} catch (e) {
				if (e instanceof WrongDevice) return this.reject(op, { code: e.code, message: e.message, retryable: true, proven: true });
				if (e instanceof LinkError) return this.reject(op, { code: "LIEN_MCF", message: e.message, retryable: true, proven: true });
				throw e;
			}
			if (st.dfn && st.dfn === inv.fn) {
				const res = this.result(op, "normalized", { data: this.fromStatus(st, inv.invoice_type, null) });
				await this.journal.setState(op.operation_id, "DONE", { result: res });
				return res;
			}
			if (st.invoice_open) await this.cancelQuietly();
			const known = st.tax_rates || {};
			for (const it of inv.items) {
				const letter = it.tax_group;
				if (Object.keys(known).length && !(letter in known))
					return this.reject(op, {
						code: "GROUPE_INCONNU_MCF", proven: true,
						message: `Le MCF ne connait que les groupes ${Object.keys(known).sort().join("")} : le groupe ${letter} demande la mise a jour du MCF (groupes FACNO v2.0).`,
					});
				if (letter in known && Math.abs(known[letter] - Number(it.tax_rate)) > 0.001)
					return this.reject(op, {
						code: "TAUX_DIFFERENTS", proven: true,
						message: `Groupe ${letter} : taux du MCF ${known[letter].toFixed(2)} %, taux ERPNext ${Number(it.tax_rate).toFixed(2)} %.`,
					});
			}
			await this.journal.setState(op.operation_id, "OPENING");
			let sub;
			try {
				await this.dev.setClient(inv.client);
				const opened = await this.dev.openInvoice(inv);
				await this.journal.setState(op.operation_id, "OPENING", { openedCounters: opened });
				for (const it of inv.items) await this.dev.addItem(it);
				for (const lid of Object.keys(inv.comments || {}).sort()) await this.dev.setComment(lid, inv.comments[lid]);
				sub = await this.dev.subtotal();
				const exp = inv.totals || {};
				if (Math.abs(sub.mv - Number(exp.mv || 0)) > this.tolerance || Math.abs(sub.mt - Number(exp.mt || 0)) > this.tolerance) {
					await this.cancelQuietly();
					return this.reject(op, {
						code: "ECART_TOTAUX", proven: true, data: { machine: sub },
						message: `Totaux du MCF TTC ${sub.mv.toFixed(2)} / TVA ${sub.mt.toFixed(2)} ; ERPNext TTC ${Number(exp.mv || 0).toFixed(2)} / TVA ${Number(exp.mt || 0).toFixed(2)} (tolerance ${this.tolerance}).`,
					});
				}
				const payments = inv.payments || [];
				if (payments.length) for (const p of payments) await this.dev.pay(p.letter, p.amount);
				else await this.dev.pay();
			} catch (e) {
				if (e instanceof DeviceRefused) {
					const [code, retryable, message] = classifyRefusal(e.deviceText);
					if (code === "NUMERO_DEJA_UTILISE") return this.check(op);
					await this.cancelQuietly();
					return this.reject(op, { code, message: `${message} (${e.command})`, retryable, deviceText: e.deviceText, proven: true });
				}
				if (e instanceof LinkError || e instanceof ProtocolError) {
					await this.cancelQuietly();
					return this.reject(op, { code: "LIEN_MCF", retryable: true, proven: true,
						message: `Liaison interrompue avant la normalisation (38h non envoyee) : ${e.message}` });
				}
				throw e;
			}
			await this.journal.setState(op.operation_id, "FINALIZING");
			let raw;
			try {
				raw = await this.dev.finalize(sub.mv, sub.mt, { expectedFn: inv.fn, pendingTimeout: this.pendingTimeout, pendingInterval: this.pendingInterval });
			} catch (e) {
				if (e instanceof DeviceRefused) {
					const [code, retryable, message] = classifyRefusal(e.deviceText);
					await this.cancelQuietly();
					return this.reject(op, { code, message, retryable, deviceText: e.deviceText, proven: true });
				}
				if (e instanceof PendingTimeout) {
					if (await this.cancelQuietly())
						return this.reject(op, { code: "NORMALISATION_EN_ATTENTE", retryable: true, proven: true,
							message: `Le MCF attend toujours le serveur DGI (${e.message}). Facture annulee sur le MCF.` });
					return this.check(op);
				}
				if (e instanceof LinkError || e instanceof ProtocolError) return this.check(op);
				throw e;
			}
			const data = Executor.securityData(raw, { machineMv: sub.mv, machineMt: sub.mt });
			if (data.fn !== inv.fn || (devInfo.nid && nidOf(data.mid) !== devInfo.nid)) {
				const res = this.result(op, "uncertain", { data, code: "REPONSE_INCOHERENTE",
					message: "La reponse 38h ne correspond pas a la facture ou au MCF attendu." });
				await this.journal.setState(op.operation_id, "UNCERTAIN", { result: res });
				return res;
			}
			const res = this.result(op, "normalized", { data });
			await this.journal.setState(op.operation_id, "DONE", { result: res });
			return res;
		}

		async check(op) {
			this.dev.exchanges = [];
			let entry = await this.journal.get(op.operation_id);
			if (entry && entry.state === "DONE" && entry.result) return entry.result;
			const fn = (op.invoice || {}).fn || op.fn || (entry || {}).fn;
			const invType = (op.invoice || {}).invoice_type || op.invoice_type || (entry && entry.payload && entry.payload.invoice_type) || "FV";
			const devInfo = op.device || {};
			if (!entry) {
				await this.journal.recordReceived(Object.assign({}, op, { op_type: op.op_type || "CHECK", fn }));
				entry = await this.journal.get(op.operation_id);
			}
			let st;
			try {
				st = await this.checkDevice(devInfo.nid, devInfo.nif);
			} catch (e) {
				if (!(e instanceof LinkError || e instanceof WrongDevice)) throw e;
				const res = this.result(op, "uncertain", { code: e.code || "LIEN_MCF",
					message: `Etat du MCF illisible, rapprochement impossible pour l'instant : ${e.message}` });
				await this.journal.setState(op.operation_id, "UNCERTAIN", { result: res });
				return res;
			}
			if (st.dfn && st.dfn === fn) {
				const res = this.result(op, "normalized", { data: this.fromStatus(st, invType, entry.opened_counters) });
				await this.journal.setState(op.operation_id, "DONE", { result: res });
				return res;
			}
			if (st.invoice_open) await this.cancelQuietly();
			return this.reject(op, { code: "NON_NORMALISEE", retryable: true, proven: true,
				message: `Rapprochement C1h : la derniere facture du MCF est ${st.dfn || "aucune"}, la facture ${fn} n'a pas ete normalisee.` });
		}

		async resync(op) {
			this.dev.exchanges = [];
			try {
				const st = await this.dev.serverStatus(true);
				return this.result(op, "done", { data: { server_status: st } });
			} catch (e) {
				if (!(e instanceof LinkError)) throw e;
				return this.result(op, "done", { data: { restart_sent: true }, code: "REDEMARRAGE",
					message: `Redemarrage demande ; le MCF ne repond plus le temps de redemarrer (${e.message}).` });
			}
		}

		async execute(op) { return this.dev.lock(() => this._execute(op)); }
		async _execute(op) {
			const kind = (op.op_type || "NORMALIZE").toUpperCase();
			if (kind === "CHECK") return this.check(op);
			if (kind === "RESYNC") return this.resync(op);
			return this.normalize(op);
		}
	}

	// ======================================================================= identity (WebCrypto)
	const SCHEME = "DGI-ECDSA-P256-V1";
	const API_PREFIX = "/api/method/dgi_compliance.gateway.api.";
	const b64 = (buf) => {
		const bytes = new Uint8Array(buf);
		let s = "";
		for (const b of bytes) s += String.fromCharCode(b);
		return btoa(s);
	};
	async function sha256hex(bytes) {
		const d = new Uint8Array(await crypto.subtle.digest("SHA-256", bytes));
		return Array.from(d, (b) => b.toString(16).padStart(2, "0")).join("");
	}
	async function fingerprint(rawPublicKey) {
		const h = (await sha256hex(rawPublicKey)).slice(0, 20).toUpperCase();
		return h.match(/.{4}/g).join("-");
	}
	function canonical(method, path, gatewayId, ts, nonce, bodyDigest) {
		return [SCHEME, method.toUpperCase(), path, gatewayId, String(ts), nonce, bodyDigest].join("\n");
	}
	function newNonce() {
		const b = new Uint8Array(16);
		crypto.getRandomValues(b);
		return Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
	}

	/** Key store: IndexedDB "dgi-mcf-keys", one non-extractable key pair per station id. */
	class KeyStore {
		constructor(dbName = "dgi-mcf-keys") { this.dbName = dbName; }
		async _db() {
			return new Promise((resolve, reject) => {
				const req = indexedDB.open(this.dbName, 1);
				req.onupgradeneeded = () => req.result.createObjectStore("keys", { keyPath: "gateway_id" });
				req.onsuccess = () => resolve(req.result);
				req.onerror = () => reject(req.error);
			});
		}
		async get(gatewayId) {
			const db = await this._db();
			return new Promise((resolve, reject) => {
				const r = db.transaction("keys").objectStore("keys").get(gatewayId);
				r.onsuccess = () => resolve(r.result || null);
				r.onerror = () => reject(r.error);
			});
		}
		async put(rec) {
			const db = await this._db();
			return new Promise((resolve, reject) => {
				const tx = db.transaction("keys", "readwrite");
				tx.objectStore("keys").put(rec);
				tx.oncomplete = () => resolve();
				tx.onerror = () => reject(tx.error);
			});
		}
		async remove(gatewayId) {
			const db = await this._db();
			return new Promise((resolve) => {
				const tx = db.transaction("keys", "readwrite");
				tx.objectStore("keys").delete(gatewayId);
				tx.oncomplete = () => resolve();
			});
		}
	}

	class Identity {
		constructor(gatewayId, keyPair, publicRaw) {
			this.gatewayId = gatewayId; this.keyPair = keyPair; this.publicRaw = publicRaw;
			this.clockOffsetS = 0;     // server time - local time (cash desk clocks are often wrong)
		}
		static async create(gatewayId, store) {
			const kp = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, false, ["sign", "verify"]);
			const raw = new Uint8Array(await crypto.subtle.exportKey("raw", kp.publicKey));
			if (store) await store.put({ gateway_id: gatewayId, keyPair: kp, publicRaw: raw, created: iso() });
			return new Identity(gatewayId, kp, raw);
		}
		static async load(gatewayId, store) {
			const rec = await store.get(gatewayId);
			return rec ? new Identity(gatewayId, rec.keyPair, new Uint8Array(rec.publicRaw)) : null;
		}
		get publicKeyB64() { return b64(this.publicRaw); }
		async fingerprint() { return fingerprint(this.publicRaw); }
		async signHeaders(method, path, bodyBytes) {
			const ts = Math.floor(Date.now() / 1000 + this.clockOffsetS);
			const nonce = newNonce();
			const msg = enc.encode(canonical(method, path, this.gatewayId, ts, nonce, await sha256hex(bodyBytes)));
			const sig = await crypto.subtle.sign({ name: "ECDSA", hash: "SHA-256" }, this.keyPair.privateKey, msg);
			return { "X-DGI-Gateway": this.gatewayId, "X-DGI-Timestamp": String(ts), "X-DGI-Nonce": nonce, "X-DGI-Signature": b64(sig) };
		}
	}


	class ServerError extends Error {
		constructor(status, message, excType) { super(`HTTP ${status} : ${message}`); this.status = status; this.excType = excType || ""; }
	}
	class Unreachable extends Error {}

	class ServerClient {
		constructor(baseUrl, identity, { operatorToken = "", fetchImpl } = {}) {
			this.base = (baseUrl || "").replace(/\/$/, "");
			this.identity = identity; this.operatorToken = operatorToken;
			this.fetch = fetchImpl || ((...a) => fetch(...a));
		}
		async call(name, payload) {
			const path = API_PREFIX + name;
			const body = enc.encode(JSON.stringify(payload || {}));
			const headers = Object.assign({ "Content-Type": "application/json", Accept: "application/json" },
				await this.identity.signHeaders("POST", path, body));
			if (this.operatorToken) headers["X-DGI-Operator"] = this.operatorToken;
			let resp;
			try {
				// never the cashier's cookies: the request is authenticated by the station key only
				resp = await this.fetch(this.base + path, { method: "POST", headers, body, credentials: "omit", cache: "no-store" });
			} catch (e) {
				throw new Unreachable(`ERPNext injoignable : ${e.message || e}`);
			}
			let data = {};
			try { data = await resp.json(); } catch (e) { data = {}; }
			if (resp.status >= 400) {
				let msg = data.exception || data.message || "";
				if (!msg && data._server_messages) {
					try { msg = JSON.parse(JSON.parse(data._server_messages)[0]).message; } catch (e) { msg = String(data._server_messages).slice(0, 300); }
				}
				throw new ServerError(resp.status, String(msg || "refus du serveur").slice(0, 500), data.exc_type);
			}
			return data && typeof data === "object" ? data.message : data;
		}
		config() { return this.call("config"); }
		heartbeat(snapshot) { return this.call("heartbeat", { snapshot }); }
		lease() { return this.call("lease"); }
		result(result) { return this.call("result", { result }); }
		event(code, message, details) { return this.call("event", { code, message, details: details || {} }); }
	}


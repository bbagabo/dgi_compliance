	// ======================================================================= protocol (protocol.py)
	const SOH = 0x01, ETX = 0x03, BRK = 0x04, AMB = 0x05, NAK = 0x15, SYN = 0x16;
	const CMD = {
		STATUS: 0xc1, SERVER: 0xc2, TAXPAYER: 0x2b, CLIENT: 0xc3, OPEN: 0xc0, ITEM: 0x31,
		SUBTOTAL: 0x33, PAYMENT: 0x35, INFO: 0x36, FINALIZE: 0x38,
	};
	const COMMAND_NAMES = {
		0xc1: "C1h etat", 0xc2: "C2h connexion DGI", 0x2b: "2Bh contribuable", 0xc3: "C3h client",
		0xc0: "C0h ouverture", 0x31: "31h article", 0x33: "33h sous-total", 0x35: "35h paiement",
		0x36: "36h ligne sup.", 0x38: "38h normalisation",
	};
	const MAX_DATA = 200, STA_LEN = 6, SEQ_MIN = 0x20, SEQ_MAX = 0xff;
	const TAX_LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
	const PROTOCOL_V1_GROUPS = 16;
	const SALE_TYPES = ["FV", "FT", "EV", "ET"], CREDIT_TYPES = ["FA", "EA"];
	const CREDIT_NATURES = ["COR", "RAN", "RAM", "RRR"];
	const CLIENT_TYPES = ["PP", "PM", "PC", "PL", "AO"], ITEM_TYPES = ["BIE", "SER", "TAX"];
	const COMMENT_IDS = "ABCDEFGH";
	const SIG_RE = /^[A-Z0-9]{24}$/;
	const enc = new TextEncoder(), dec = new TextDecoder("utf-8", { fatal: false });

	class ProtocolError extends Error {}
	class LinkError extends Error {}
	class DeviceRefused extends Error {
		constructor(command, deviceText, code) {
			super(`${command} : ${deviceText}`);
			this.command = command; this.deviceText = deviceText; this.code = code || "REFUS_MCF";
		}
	}
	class PendingTimeout extends Error {}
	class WrongDevice extends Error {
		constructor(code, message, status) { super(message); this.code = code; this.status = status || {}; }
	}

	const ESCAPES = [["&", "^amp;"], ["\r", "^xa;"], ["\n", "^xd;"], [",", "^x2c;"], ["<", "^lt;"], [">", "^gt;"]];
	const CONTROL_RE = /[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/g;

	function escapeText(value) {
		let s = value === null || value === undefined ? "" : String(value);
		s = s.replace(/\t/g, " ").replace(CONTROL_RE, "");
		for (const [raw, rep] of ESCAPES) s = s.split(raw).join(rep);
		return s;
	}
	function unescapeText(value) {
		let s = value || "";
		for (const [raw, rep] of [...ESCAPES].reverse()) s = s.split(rep).join(raw);
		return s;
	}
	function truncateUtf8(escaped, maxBytes) {
		let out = "", size = 0;
		for (const tok of (escaped || "").match(/\^[a-z0-9]+;|[\s\S]/gu) || []) {
			const n = enc.encode(tok).length;
			if (size + n > maxBytes) break;
			out += tok; size += n;
		}
		return out;
	}
	function field(value, maxBytes) {
		const s = escapeText(value);
		return maxBytes ? truncateUtf8(s, maxBytes) : s;
	}
	function round2(x) {
		const v = Math.round((Number(x || 0) + Number.EPSILON) * 100) / 100;
		return v === 0 ? 0 : v;
	}
	const fmtAmount = (v) => round2(v).toFixed(2);
	const fmtRate = (v) => Number(v || 0).toFixed(2);
	function fmtQty(v) {
		const s = Number(v === null || v === undefined || v === "" ? 1 : v).toFixed(3);
		return s.replace(/0+$/, "").replace(/\.$/, "");
	}
	function toFloat(v, dflt = 0) {
		const n = parseFloat(String(v === null || v === undefined ? "" : v).trim());
		return Number.isFinite(n) && /^\s*[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?\s*$/.test(String(v)) ? n : dflt;
	}

	function bcc16(core) {
		let total = 0;
		for (const b of core) total = (total + b) & 0xffff;
		return Uint8Array.from([12, 8, 4, 0].map((sh) => 0x30 + ((total >> sh) & 0xf)));
	}
	const nextSeq = (seq) => (seq >= SEQ_MAX || seq < SEQ_MIN ? SEQ_MIN : seq + 1);

	function buildFrame(seq, cmd, data) {
		data = data || new Uint8Array(0);
		if (seq < SEQ_MIN || seq > SEQ_MAX) throw new ProtocolError(`SEQ hors plage : ${seq}`);
		if (data.length > MAX_DATA) throw new ProtocolError(`donnees de ${data.length} octets : ${MAX_DATA} au maximum`);
		const core = new Uint8Array(3 + data.length + 1);
		core[0] = 0x20 + 4 + data.length; core[1] = seq; core[2] = cmd;
		core.set(data, 3); core[core.length - 1] = AMB;
		const frame = new Uint8Array(1 + core.length + 4 + 1);
		frame[0] = SOH; frame.set(core, 1); frame.set(bcc16(core), 1 + core.length); frame[frame.length - 1] = ETX;
		return frame;
	}
	function sameBytes(a, b) { return a.length === b.length && a.every((x, i) => x === b[i]); }

	function parseResponseFrame(frame) {
		if (frame.length < 1 + 3 + 1 + STA_LEN + 1 + 4 + 1) throw new ProtocolError(`trame trop courte (${frame.length} octets)`);
		if (frame[0] !== SOH || frame[frame.length - 1] !== ETX) throw new ProtocolError("SOH/ETX absents");
		const core = frame.slice(1, frame.length - 5), rx = frame.slice(frame.length - 5, frame.length - 1);
		if (!sameBytes(bcc16(core), rx)) throw new ProtocolError("BCC invalide");
		if ((core.length + 0x20) % 256 !== core[0]) throw new ProtocolError("longueur differente du champ LEN");
		if (core[core.length - 1] !== AMB) throw new ProtocolError("delimiteur AMB absent");
		const brk = core.length - 1 - STA_LEN - 1;
		if (brk < 3 || core[brk] !== BRK) throw new ProtocolError("delimiteur BRK absent");
		const data = core.slice(3, brk);
		return { seq: core[1], cmd: core[2], data, sta: core.slice(brk + 1, brk + 1 + STA_LEN), text: dec.decode(data) };
	}

	const STATUS_BITS = [
		[0, 2, "date_heure_non_reglee"], [0, 1, "commande_non_valide"], [0, 0, "erreur_syntaxe"],
		[1, 4, "rapport_quotidien_requis"], [1, 2, "memoire_reinitialisee"], [1, 1, "commande_interdite_mode_actuel"],
		[1, 0, "depassement_sommes_rapport"], [2, 3, "facture_ouverte"], [4, 4, "memoire_pleine"],
		[4, 3, "memoire_moins_50"], [4, 2, "enregistrement_invalide"], [4, 0, "erreur_ecriture_memoire"],
	];
	const BLOCKING_FLAGS = ["memoire_pleine", "enregistrement_invalide", "erreur_ecriture_memoire"];
	function statusFlags(sta) {
		return STATUS_BITS.filter(([i, bit]) => i < sta.length && ((sta[i] >> bit) & 1)).map((x) => x[2]);
	}
	const invoiceOpen = (sta) => sta.length > 2 && Boolean((sta[2] >> 3) & 1);

	function classify(text) {
		const t = (text || "").trim(), up = t.toUpperCase();
		for (const kind of ["E", "P", "R"]) if (up.startsWith(kind + ":")) return [kind, t.slice(2).trim()];
		if (up === "R" || /^R\s*-?\d/.test(up)) return ["R", t.slice(1).trim()];
		if (up.startsWith("E") && up.length <= 2) return ["E", ""];
		return ["DATA", t];
	}
	const splitFields = (text) => (text || "").split(",").map((x) => unescapeText(x).trim());
	function nidOf(mid) {
		mid = (mid || "").trim();
		const i = mid.lastIndexOf("-");
		return i >= 0 ? mid.slice(0, i) : mid;
	}

	function parseStatus(text) {
		const f = splitFields(text);
		const keys = ["mid", "nif", "dt", "tc", "fvc", "frc", "dfdt", "dft", "dfs", "dfn", "dmv"];
		const out = {};
		keys.forEach((k, i) => { out[k] = i < f.length ? f[i] : ""; });
		out.nid = nidOf(out.mid);
		out.complete = f.length >= keys.length;
		out.tax_rates = {};
		const rates = f.slice(keys.length).slice(0, TAX_LETTERS.length);
		rates.forEach((v, j) => { if (v !== "") out.tax_rates[TAX_LETTERS[j]] = toFloat(v); });
		out.group_count = rates.length;
		return out;
	}
	function parseServerStatus(text) {
		const f = splitFields(text);
		return { sent: f[0] || "", pending: f[1] || "", last_sync: f[2] || "", state: f[3] || "", error: f[4] || "" };
	}
	function parseOpenInvoice(text) {
		const f = splitFields(text);
		return { fc: f[0] || "", tc: f[1] || "" };
	}
	function subtotalLayout(n, groupCount) {
		const candidates = [];
		for (const [layout, base, extra] of [["spec", 1, 3], ["eltrade", 2, 4]]) {
			if ((n - extra) % 2 === 0) {
				const g = (n - extra) / 2;
				if (g >= PROTOCOL_V1_GROUPS && g <= TAX_LETTERS.length) candidates.push([layout, base, g]);
			}
		}
		if (groupCount) for (const c of candidates) if (c[2] === groupCount) return c;
		if (!candidates.length) throw new ProtocolError(`sous-total 33h illisible (${n} champs)`);
		return candidates[0];
	}
	function parseSubtotal(text, groupCount) {
		const f = splitFields(text).map((x) => toFloat(x));
		const [layout, base, g] = subtotalLayout(f.length, groupCount);
		const groups = {};
		for (let i = 0; i < g; i++) {
			const total = f[base + i], vat = f[base + g + i];
			if (total || vat) groups[TAX_LETTERS[i]] = { total: round2(total), vat: round2(vat) };
		}
		const mtSum = round2(Object.values(groups).reduce((a, x) => a + x.vat, 0));
		return {
			mv: round2(f[0]), mt: round2(layout === "eltrade" ? f[1] : mtSum), mts: round2(f[base + 2 * g]),
			mcur: round2(f[base + 2 * g + 1]), groups, layout: layout + f.length, group_count: g,
		};
	}
	function parsePayment(text) {
		const [kind, payload] = classify(text);
		if (kind !== "R") throw new ProtocolError(`reponse 35h inattendue : ${text}`);
		return toFloat(payload.replace(/^:+/, ""), 0);
	}
	function parseNormalized(payload, expectedFn) {
		const f = splitFields(payload);
		if (f.length < 8) throw new ProtocolError(`reponse 38h incomplete : ${payload}`);
		const a = f[6], b = f[7];
		let fn = a, sig = b;
		if (expectedFn && a === expectedFn) { fn = a; sig = b; }
		else if (expectedFn && b === expectedFn) { fn = b; sig = a; }
		else if (SIG_RE.test(b.toUpperCase()) && !SIG_RE.test(a.toUpperCase())) { fn = a; sig = b; }
		else if (SIG_RE.test(a.toUpperCase()) && !SIG_RE.test(b.toUpperCase())) { fn = b; sig = a; }
		return { fc: f[0], tc: f[1], ft: f[2], dt: f[3], mid: f[4], nif: f[5], fn, sig: sig.toUpperCase() };
	}

	function clientData(client) {
		const c = client || {};
		const ctype = (c.ctype || "PP").toUpperCase();
		if (!CLIENT_TYPES.includes(ctype)) throw new ProtocolError(`type de client invalide : ${ctype}`);
		return [ctype, field(c.cnif, 20), field(c.cnom, 64), field(c.cadd, 64), field(c.ctel, 24),
			field(c.ceml, 48), field(c.crccm, 32)].join(",");
	}
	function openInvoiceData(inv) {
		const op = inv.operator || {};
		const parts = [field(op.id || "SFE", 16), field(op.name || "SFE", 32), field(inv.nif, 20)];
		const itype = inv.invoice_type;
		if (CREDIT_TYPES.includes(itype)) {
			const cn = inv.credit_note || {};
			if (!CREDIT_NATURES.includes(cn.rr)) throw new ProtocolError("nature de l'avoir obligatoire (COR, RAN, RAM ou RRR)");
			const rn = (cn.rn || "").replace(/-/g, "").trim();
			if (cn.rr !== "RRR" && rn.length !== 24)
				throw new ProtocolError("la reference d'un avoir est le Code DEF/DGI de 24 caracteres de la facture d'origine");
			parts.push(itype, cn.rr, field(cn.rr !== "RRR" || rn ? rn : "RRR", 64));
		} else if (SALE_TYPES.includes(itype)) {
			parts.push(itype);
		} else {
			throw new ProtocolError(`type de facture invalide : ${itype}`);
		}
		parts.push((inv.pmode || "TTC").toUpperCase(), field(inv.isf, 20), field(inv.fn, 64));
		if (inv.exchange) parts.push(fmtAmount(inv.exchange.crt), String(inv.exchange.cdt).slice(0, 8));
		return parts.join(",");
	}
	function itemData(it) {
		const letter = (it.tax_group || "").toUpperCase();
		if (letter.length !== 1 || !TAX_LETTERS.includes(letter)) throw new ProtocolError(`groupe de taxation invalide : ${letter || "?"} (A a Z)`);
		const itype = (it.itype || "BIE").toUpperCase();
		if (!ITEM_TYPES.includes(itype)) throw new ProtocolError(`type d'article invalide : ${itype}`);
		let head = field(it.name || "ARTICLE", 64);
		if (it.desc) head += "\n" + field(it.desc, 24);
		let data = `${head}\t${itype},${letter}${fmtRate(it.tax_rate)}%${fmtAmount(it.amount)}\t${fmtAmount(it.price)}`;
		const qty = Number(it.qty || 1);
		if (Math.abs(qty - 1) > 1e-9) data += "*" + fmtQty(qty);
		if (it.ts_value !== null && it.ts_value !== undefined && it.ts_value !== "") {
			let ts = `;T${String(it.ts_value).trim()},${fmtAmount(it.ts_total || 0)}`;
			if (it.ts_desc) ts += "," + field(it.ts_desc, 16);
			data += ts;
		}
		if (it.orig_price) data += `\t${fmtAmount(it.orig_price)},${field(it.price_desc || "Remise", 24)}`;
		return data;
	}
	function commentData(lineId, content) {
		const lid = (lineId || "").toUpperCase();
		if (lid.length !== 1 || !COMMENT_IDS.includes(lid)) throw new ProtocolError(`ligne supplementaire invalide : ${lineId}`);
		return `${lid},${field(content, 255)}`;
	}
	function paymentData(letter, amount) {
		if (!letter) return "";
		letter = letter.toUpperCase();
		if (!/^[A-Z]$/.test(letter)) throw new ProtocolError(`mode de paiement invalide : ${letter}`);
		return letter + (amount !== null && amount !== undefined ? fmtAmount(amount) : "");
	}
	const finalizeData = (mv, mt) => `${fmtAmount(mv)},${fmtAmount(mt)}`;
	const qrContent = (mid, sig, nif, dt) => `RDCDEF01;${mid};${sig};${nif};${dt}`;
	function hex(bytes) { return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join(" "); }

	// ======================================================================= device (device.py)
	const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
	const now = () => (typeof performance !== "undefined" ? performance.now() : Date.now());

	class MCFDevice {
		constructor(transport, opts = {}) {
			this.t = transport;
			this.responseTimeout = Math.max(500, opts.responseTimeout || 600);   // protocol 3.1: >= 500 ms
			this.retries = opts.retries || 3;
			this.maxSynWait = opts.maxSynWait || 15000;
			this.seq = opts.startSeq >= SEQ_MIN && opts.startSeq <= SEQ_MAX ? opts.startSeq : SEQ_MIN;
			this.lastSta = new Uint8Array(0);
			this.groupCount = null;
			this.exchanges = [];
			this.trace = opts.trace || null;    // (direction, bytes, label) -> diagnostic log of the page
			this._tail = Promise.resolve();
		}
		/** Runs fn alone on the MCF: an invoice (C3h..38h) is never interleaved with another command
		 *  (station cycle, heartbeat, diagnostic buttons of the page). */
		lock(fn) {
			const run = this._tail.then(() => fn());
			this._tail = run.catch(() => {});
			return run;
		}
		get port() { return this.t.name || "?"; }
		async close() { await this.t.close(); }

		async readFrame(timeout) {
			let deadline = now() + timeout;
			const synLimit = now() + this.maxSynWait;
			const buf = [];
			for (;;) {
				const remaining = deadline - now();
				if (remaining <= 0) return null;
				const chunk = await this.t.read(1, Math.min(remaining, 200));
				if (!chunk || !chunk.length) continue;
				const b = chunk[0];
				if (!buf.length) {
					if (b === NAK) return "NAK";
					if (b === SYN) { deadline = Math.min(synLimit, Math.max(deadline, now() + 500)); continue; }
					if (b !== SOH) continue;
				}
				buf.push(b);
				if (b === ETX && buf.length >= 14) return Uint8Array.from(buf);
			}
		}

		async transact(cmd, data = "", timeout) {
			const payload = typeof data === "string" ? enc.encode(data) : data || new Uint8Array(0);
			const name = COMMAND_NAMES[cmd] || "0x" + cmd.toString(16);
			if (payload.length > MAX_DATA)
				throw new ProtocolError(`${name} : ${payload.length} octets, le MCF en accepte ${MAX_DATA} au maximum`);
			this.seq = nextSeq(this.seq);
			const seq = this.seq, frame = buildFrame(seq, cmd, payload);
			timeout = timeout || this.responseTimeout;
			let lastProblem = "pas de reponse";
			for (let attempt = 1; attempt <= this.retries; attempt++) {
				this.t.resetInput();
				if (this.trace) this.trace(">", frame, name);
				await this.t.write(frame);
				const reply = await this.readFrame(timeout);
				if (reply === "NAK") { lastProblem = "NAK"; if (this.trace) this.trace("<", [NAK], "NAK"); continue; }
				if (reply === null) { lastProblem = "pas de reponse"; continue; }
				if (this.trace) this.trace("<", reply, name);
				let resp;
				try { resp = parseResponseFrame(reply); } catch (e) { lastProblem = e.message; continue; }
				if (resp.seq !== seq || resp.cmd !== cmd) { lastProblem = "reponse d'un autre echange"; continue; }
				this.lastSta = resp.sta;
				this.exchanges.push({ cmd: name, reply: resp.text.slice(0, 80), flags: statusFlags(resp.sta) });
				return resp;
			}
			throw new LinkError(`le MCF ne repond pas a ${name} sur ${this.port} (${lastProblem})`);
		}
		async checked(cmd, data = "", timeout, label) {
			const resp = await this.transact(cmd, data, timeout);
			const [kind, payload] = classify(resp.text);
			if (kind === "E") throw new DeviceRefused(label || COMMAND_NAMES[cmd], payload || resp.text);
			return resp.text;
		}
		async status() {
			const resp = await this.transact(CMD.STATUS);
			const st = parseStatus(resp.text);
			st.flags = statusFlags(resp.sta);
			st.invoice_open = invoiceOpen(resp.sta);
			if (st.group_count) this.groupCount = st.group_count;
			return st;
		}
		async serverStatus(restart = false) {
			const resp = await this.transact(CMD.SERVER, restart ? "RESTART" : "", 3000);
			return parseServerStatus(resp.text);
		}
		async taxpayer(opt) { return unescapeText((await this.transact(CMD.TAXPAYER, opt)).text); }
		async setClient(client) { await this.checked(CMD.CLIENT, clientData(client)); }
		async openInvoice(inv) { return parseOpenInvoice(await this.checked(CMD.OPEN, openInvoiceData(inv), 3000)); }
		async addItem(it) {
			return this.checked(CMD.ITEM, itemData(it), 3000, `31h article « ${String(it.name || "").slice(0, 24)} »`);
		}
		async setComment(lineId, content) { await this.checked(CMD.INFO, commentData(lineId, content)); }
		async subtotal() { return parseSubtotal(await this.checked(CMD.SUBTOTAL, "", 3000), this.groupCount); }
		async pay(letter, amount) { return parsePayment(await this.checked(CMD.PAYMENT, paymentData(letter, amount), 3000)); }
		async finalize(mv, mt, { expectedFn, pendingTimeout = 90000, pendingInterval = 1500, onPending } = {}) {
			const data = finalizeData(mv, mt);
			const deadline = now() + pendingTimeout;
			for (;;) {
				const resp = await this.transact(CMD.FINALIZE, data, 5000);
				const [kind, payload] = classify(resp.text);
				if (kind === "E") throw new DeviceRefused("38h normalisation", payload);
				if (kind === "P") {
					if (onPending) onPending(payload);
					if (now() >= deadline) throw new PendingTimeout(payload);
					await sleep(pendingInterval);
					continue;
				}
				return parseNormalized(kind === "R" ? payload : resp.text, expectedFn);
			}
		}
		async cancel() { return (await this.transact(CMD.FINALIZE, "C", 3000)).text; }
	}

	// ======================================================================= journal
	const OPEN_STATES = ["RECEIVED", "OPENING", "FINALIZING", "UNCERTAIN"];
	const iso = () => new Date().toISOString();

	/** Only identifiers and results are kept (no customer data): enough for the C1h reconciliation. */
	function minimal(op) {
		const inv = op.invoice || {};
		return {
			operation_id: op.operation_id, op_type: op.op_type || "NORMALIZE", fn: inv.fn || op.fn,
			invoice_type: inv.invoice_type || op.invoice_type, device: op.device || {},
		};
	}

	class MemoryJournal {
		constructor() { this.rows = new Map(); }
		async get(id) { const r = this.rows.get(id); return r ? JSON.parse(JSON.stringify(r)) : null; }
		async _put(r) { this.rows.set(r.op_id, JSON.parse(JSON.stringify(r))); }
		async all() { return [...this.rows.values()].map((r) => JSON.parse(JSON.stringify(r))); }
		async recordReceived(op) {
			const row = await this.get(op.operation_id);
			if (row) { row.lease_token = op.lease_token; row.updated_at = iso(); await this._put(row); return row; }
			const m = minimal(op);
			const r = {
				op_id: op.operation_id, op_type: m.op_type, fn: m.fn, state: "RECEIVED", lease_token: op.lease_token,
				payload: m, result: null, opened_counters: null, delivered_at: null, created_at: iso(), updated_at: iso(),
			};
			await this._put(r);
			return this.get(op.operation_id);
		}
		async setState(id, state, { result, openedCounters } = {}) {
			const r = await this.get(id);
			if (!r) return;
			r.state = state; r.updated_at = iso();
			if (result !== undefined) { r.result = result; r.delivered_at = null; }
			if (openedCounters !== undefined) r.opened_counters = openedCounters;
			await this._put(r);
		}
		async findDoneByFn(fn) {
			const rows = (await this.all()).filter((r) => r.fn === fn && r.state === "DONE");
			rows.sort((a, b) => (a.updated_at < b.updated_at ? 1 : -1));
			return rows[0] || null;
		}
		async openOperations() {
			const rows = (await this.all()).filter((r) => OPEN_STATES.includes(r.state));
			rows.sort((a, b) => (a.created_at > b.created_at ? 1 : -1));
			return rows;
		}
		async undelivered() {
			return (await this.all()).filter((r) => r.result && !r.delivered_at && ["DONE", "REJECTED", "UNCERTAIN"].includes(r.state));
		}
		async markDelivered(id) {
			const r = await this.get(id);
			if (r) { r.delivered_at = iso(); await this._put(r); }
		}
		async purge(days = 30) {
			const limit = new Date(Date.now() - days * 86400000).toISOString();
			for (const r of await this.all())
				if (r.delivered_at && r.updated_at < limit && !OPEN_STATES.includes(r.state)) this.rows.delete(r.op_id);
		}
	}

	/** IndexedDB journal (browser). Same interface; one store keyed by op_id. */
	class IDBJournal extends MemoryJournal {
		constructor(dbName) { super(); this.dbName = dbName; this.db = null; }
		async open() {
			this.db = await new Promise((resolve, reject) => {
				const req = indexedDB.open(this.dbName, 1);
				req.onupgradeneeded = () => req.result.createObjectStore("operations", { keyPath: "op_id" });
				req.onsuccess = () => resolve(req.result);
				req.onerror = () => reject(req.error);
			});
			return this;
		}
		_tx(mode, fn) {
			return new Promise((resolve, reject) => {
				const tx = this.db.transaction("operations", mode, { durability: "strict" });
				const out = fn(tx.objectStore("operations"));
				tx.oncomplete = () => resolve(out && out.result !== undefined ? out.result : undefined);
				tx.onerror = () => reject(tx.error);
				tx.onabort = () => reject(tx.error);
			});
		}
		async get(id) { return (await this._tx("readonly", (s) => s.get(id))) || null; }
		async _put(r) { await this._tx("readwrite", (s) => s.put(r)); }
		async all() { return (await this._tx("readonly", (s) => s.getAll())) || []; }
		async purge(days = 30) {
			const limit = new Date(Date.now() - days * 86400000).toISOString();
			for (const r of await this.all())
				if (r.delivered_at && r.updated_at < limit && !OPEN_STATES.includes(r.state))
					await this._tx("readwrite", (s) => s.delete(r.op_id));
		}
	}


"""Authentication of the site gateways (signed requests, no shared secret).

Two kinds of gateway, same server path:
  * "Poste navigateur": the ERPNext page "Poste MCF" in Chrome/Edge on the cash desk where the MCF
    is plugged (Web Serial). Its ECDSA P-256 key is generated by WebCrypto as NON-EXTRACTABLE and
    kept in the browser profile. Each request also carries an operator token obtained by a
    logged-in user holding the role DGI Caisse MCF (two factors: approved device + person).
  * "Service (poste dedie)": the dgi-gateway program (Ed25519 key, DPAPI / file 0600).

A request is accepted when:
  * the gateway exists and is Active (approved by a DGI Fiscal Manager, not revoked);
  * it has no query string and a bounded body (the signature covers the body only);
  * the timestamp is within MAX_CLOCK_SKEW_S of the server clock;
  * the signature of the canonical string (signing.canonical) is valid for the key type stored at
    enrolment (never chosen by the request);
  * the nonce was never seen (stored 10 minutes in Redis: replay protection);
  * for a browser station, the operator token is valid for THIS gateway and its user still active.
Requests are sent WITHOUT session cookies: the request then runs as the technical user of THAT
gateway (role DGI Gateway, no desk access), restricted to its own MCF. The cashier's session is
never switched (frappe.set_user on a real session would overwrite it).
"""
import base64
import secrets
import time

import frappe
from frappe import _

from dgi_compliance.gateway import signing

NONCE_TTL_S = 600
MAX_BODY_BYTES = 256 * 1024
ALG_ED25519 = "Ed25519"
ALG_P256 = "ECDSA-P256"
KIND_BROWSER = "Poste navigateur"
KIND_SERVICE = "Service (poste dedie)"
STATION_ROLES = ("DGI Caisse MCF", "DGI Fiscal Manager", "System Manager")
OPERATOR_TOKEN_TTL_S = 12 * 3600
HEADER_OPERATOR = "X-DGI-Operator"


class GatewayAuthError(frappe.AuthenticationError):
    pass


def _header(name):
    return (frappe.get_request_header(name) or "").strip()


def _public_key(b64: str, algorithm: str = ALG_ED25519):
    raw = base64.b64decode(b64 or "", validate=True)
    if algorithm == ALG_P256:
        from cryptography.hazmat.primitives.asymmetric import ec
        if len(raw) != 65 or raw[0] != 4:
            raise GatewayAuthError(_("Cle publique de poste invalide."))
        return ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), raw)
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    if len(raw) != 32:
        raise GatewayAuthError(_("Cle publique de passerelle invalide."))
    return Ed25519PublicKey.from_public_bytes(raw)


def verify_signature(public_key_b64, method, path, gateway_id, timestamp, nonce, body, signature_b64,
                     algorithm: str = ALG_ED25519) -> bool:
    from cryptography.exceptions import InvalidSignature
    try:
        sig = base64.b64decode(signature_b64 or "", validate=True)
        key = _public_key(public_key_b64, algorithm)
        if algorithm == ALG_P256:
            from cryptography.hazmat.primitives import hashes
            from cryptography.hazmat.primitives.asymmetric import ec
            from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature
            if len(sig) != 64:
                return False
            der = encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
            msg = signing.canonical(method, path, gateway_id, timestamp, nonce, body, signing.SCHEME_ECDSA_P256)
            key.verify(der, msg, ec.ECDSA(hashes.SHA256()))
        else:
            key.verify(sig, signing.canonical(method, path, gateway_id, timestamp, nonce, body))
        return True
    except (InvalidSignature, ValueError, TypeError, GatewayAuthError):
        return False
    except Exception:
        return False


def _claim_nonce(gateway_id: str, nonce: str) -> bool:
    """SET NX in Redis: False when the nonce was already used (replayed request)."""
    key = frappe.cache.make_key(f"dgi_gw_nonce|{gateway_id}|{nonce}", shared=True)
    return bool(frappe.cache.set(key, 1, ex=NONCE_TTL_S, nx=True))


# --------------------------------------------------------------------------- operator tokens
def _op_key(gateway_id, token):
    return frappe.cache.make_key(f"dgi_station_op|{gateway_id}|{token}", shared=True)


def issue_operator_token(gateway_id: str, user: str) -> str:
    token = secrets.token_urlsafe(32)
    frappe.cache.set(_op_key(gateway_id, token), user, ex=OPERATOR_TOKEN_TTL_S)
    return token


def revoke_operator_token(gateway_id: str, token: str) -> None:
    if token:
        frappe.cache.delete(_op_key(gateway_id, token))


def operator_of(gateway_id: str, token: str) -> str | None:
    if not token or len(token) > 100:
        return None
    user = frappe.cache.get(_op_key(gateway_id, token))
    if isinstance(user, bytes):
        user = user.decode()
    return user or None


def user_may_operate(user: str) -> bool:
    if not user or user == "Guest" or not frappe.db.get_value("User", user, "enabled"):
        return False
    return bool(set(frappe.get_roles(user)) & set(STATION_ROLES))


def _reject(event_code, message, gateway=None):
    from dgi_compliance.gateway.events import log_event
    try:
        log_event(gateway, event_code, message, level="Alerte",
                  details={"ip": getattr(frappe.local, "request_ip", None), "path": frappe.request.path})
        frappe.db.commit()
    except Exception:
        pass
    raise GatewayAuthError(message)


def authenticate(require_active=True):
    """Verify the signed request and return the DGI Gateway document. Switches the (guest)
    request to the gateway's technical user when the gateway is Active."""
    if frappe.session.user != "Guest":
        # a gateway request never carries a desk session (see module docstring)
        raise GatewayAuthError(_("Requete de passerelle refusee : session utilisateur presente."))
    gateway_id = _header(signing.HEADER_GATEWAY)
    ts, nonce, sig = _header(signing.HEADER_TIMESTAMP), _header(signing.HEADER_NONCE), _header(signing.HEADER_SIGNATURE)
    if not (gateway_id and ts and nonce and sig):
        raise GatewayAuthError(_("Requete de passerelle non signee."))
    if not frappe.db.exists("DGI Gateway", gateway_id):
        raise GatewayAuthError(_("Passerelle inconnue."))
    gw = frappe.get_doc("DGI Gateway", gateway_id)
    if not gw.public_key:
        _reject("SIGNATURE_REFUSEE", _("Passerelle non enrolee."), gw.name)
    if frappe.request.query_string:
        _reject("REQUETE_INVALIDE", _("Parametres d'URL interdits sur une requete de passerelle."), gw.name)
    body = frappe.request.get_data(cache=True) or b""
    if len(body) > MAX_BODY_BYTES:
        _reject("REQUETE_INVALIDE", _("Requete trop volumineuse ({0} octets).").format(len(body)), gw.name)
    try:
        skew = abs(time.time() - int(ts))
    except ValueError:
        skew = 10 ** 9
    if skew > signing.MAX_CLOCK_SKEW_S:
        _reject("HORLOGE", _("Horodatage hors fenetre ({0} s) : verifiez l'heure du poste.").format(int(min(skew, 10 ** 6))), gw.name)
    algorithm = gw.get("key_algorithm") or ALG_ED25519
    if not verify_signature(gw.public_key, frappe.request.method, frappe.request.path, gateway_id, ts, nonce, body,
                            sig, algorithm):
        _reject("SIGNATURE_REFUSEE", _("Signature de passerelle invalide."), gw.name)
    if not _claim_nonce(gateway_id, nonce):
        _reject("REJEU", _("Requete deja recue (rejeu refuse)."), gw.name)
    station_user = None
    if (gw.get("kind") or KIND_SERVICE) == KIND_BROWSER and require_active:
        station_user = operator_of(gw.name, _header(HEADER_OPERATOR))
        if not station_user or not user_may_operate(station_user):
            _reject("OPERATEUR_REFUSE", _("Poste MCF : aucun operateur connecte (ouvrez la page Poste MCF avec un "
                                          "utilisateur DGI Caisse MCF)."), gw.name)
    if require_active:
        if gw.status != "Active" or not gw.api_user:
            raise GatewayAuthError(_("Passerelle {0} : statut {1}.").format(gw.name, gw.status))
        if not frappe.db.get_value("User", gw.api_user, "enabled"):
            raise GatewayAuthError(_("Utilisateur technique de la passerelle desactive."))
        frappe.set_user(gw.api_user)
    frappe.local.dgi_gateway = gw.name
    frappe.local.dgi_station_user = station_user
    return gw
